HDR = "| 卷型 | 目录 | 覆盖题目 | 文件内收录的机构/名师口径（脚本提取） | 备注 |\n|------|------|:--:|------|------|"

def table(rows):
    out = [HDR]
    for a, b, c, d, e in rows:
        out.append("| %s | `%s` | %s | %s | %s |" % (a, b, c, d, e))
    return out

lines = io.open(P, encoding='utf-8').read().split('\n')

def splice(lines, header_prefix, new_block):
    start = next(i for i, l in enumerate(lines) if l.startswith(header_prefix))
    end = start
    while end < len(lines) and lines[end].startswith('|'):
        end += 1
    return lines[:start] + new_block + lines[end:]

